export type MessageKey = keyof typeof hebrew
export type Language = 'en' | 'he'
export type Values = Record<string, string | number>
export type Translate = (key: MessageKey, values?: Values) => string

export function translate(language: Language, key: MessageKey, values: Values = {}): string {
  const template: string = language === 'he' ? hebrew[key] : key
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`))
}
